type categoriesServiceStub struct {
	created map[string]interface{}
	updated map[string]interface{}
	err     error
}

func (stub *categoriesServiceStub) GetAll() (*[]entities.Category, error) {
	categories := []entities.Category{}
	return &categories, nil
}

func (stub *categoriesServiceStub) GetByID(string) (*entities.Category, error) {
	if stub.err != nil {
		return nil, stub.err
	}
	return &entities.Category{ID: "6ba7b810-9dad-11d1-80b4-00c04fd430c8", Name: "Tools"}, nil
}

func (stub *categoriesServiceStub) Create(data map[string]interface{}) error {
	stub.created = data
	return stub.err
}

func (stub *categoriesServiceStub) Update(_ string, data map[string]interface{}) error {
	stub.updated = data
	return stub.err
}

func (stub *categoriesServiceStub) Delete(string) error {
	return stub.err
}

var _ services.ICategoriesService = (*categoriesServiceStub)(nil)

func TestCreateCategoryUsesSchemaAndDatabaseDefaults(t *testing.T) {
	service := &categoriesServiceStub{}
	app := fiber.New()
	GatewayCategories(HTTPGateway{CategoriesService: service}, app)

	request := httptest.NewRequest(http.MethodPost, "/api/v1/categories/create_category", strings.NewReader(`{"name":"Tools","description":"Hand tools"}`))
	request.Header.Set("Content-Type", "application/json")
	response, err := app.Test(request)
	if err != nil {
		t.Fatal(err)
	}
	defer response.Body.Close()

	if response.StatusCode != http.StatusCreated {
		t.Fatalf("unexpected status: %d", response.StatusCode)
	}
	if service.created["name"] != "Tools" || service.created["description"] != "Hand tools" {
		t.Fatalf("unexpected category passed to service: %#v", service.created)
	}
	if _, exists := service.created["id"]; exists {
		t.Fatalf("id should be generated by the database: %#v", service.created)
	}
	if _, exists := service.created["created_at"]; exists {
		t.Fatalf("created_at should be generated by the database: %#v", service.created)
	}
}

func TestUpdateCategoryCanClearDescriptionAndRejectsEmptyName(t *testing.T) {
	service := &categoriesServiceStub{}
	app := fiber.New()
	gateway := HTTPGateway{CategoriesService: service}
	GatewayCategories(gateway, app)
	app.Patch("/api/v1/categories/:id", gateway.UpdateCategory)

	request := httptest.NewRequest(http.MethodPatch, "/api/v1/categories/6ba7b810-9dad-11d1-80b4-00c04fd430c8", strings.NewReader(`{"description":null}`))
	request.Header.Set("Content-Type", "application/json")
	response, err := app.Test(request)
	if err != nil {
		t.Fatal(err)
	}
	response.Body.Close()

	description, descriptionSet := service.updated["description"]
	if response.StatusCode != http.StatusOK || !descriptionSet || description != nil {
		t.Fatalf("unexpected status or update body: %d, %#v", response.StatusCode, service.updated)
	}

	invalid := httptest.NewRequest(http.MethodPost, "/api/v1/categories/create_category", strings.NewReader(`{"name":"  "}`))
	invalid.Header.Set("Content-Type", "application/json")
	response, err = app.Test(invalid)
	if err != nil {
		t.Fatal(err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusUnprocessableEntity {
		t.Fatalf("unexpected validation status: %d", response.StatusCode)
	}
}

func TestCategoryEndpointsReturnNotFoundAndConflict(t *testing.T) {
	const categoryPath = "/api/v1/categories/6ba7b810-9dad-11d1-80b4-00c04fd430c8"
	for _, test := range []struct {
		name       string
		serviceErr error
		method     string
		path       string
		wantStatus int
	}{
		{"get missing", repositories.ErrCategoryNotFound, http.MethodGet, categoryPath, http.StatusNotFound},
		{"delete missing", repositories.ErrCategoryNotFound, http.MethodDelete, categoryPath, http.StatusNotFound},
		{"duplicate name", repositories.ErrCategoryConflict, http.MethodPost, "/api/v1/categories/create_category", http.StatusConflict},
	} {
		t.Run(test.name, func(t *testing.T) {
			service := &categoriesServiceStub{err: test.serviceErr}
			app := fiber.New()
			GatewayCategories(HTTPGateway{CategoriesService: service}, app)

			request := httptest.NewRequest(test.method, test.path, strings.NewReader(`{"name":"Tools"}`))
			request.Header.Set("Content-Type", "application/json")
			response, err := app.Test(request)
			if err != nil {
				t.Fatal(err)
			}
			defer response.Body.Close()
			if response.StatusCode != test.wantStatus {
				t.Fatalf("status = %d, want %d", response.StatusCode, test.wantStatus)
			}
		})
	}
}
